-- =============================================
-- MIGRACIÓN: Páginas de descargables con QR
-- Página (ej. "fuentes") → PDFs descargables
-- URL pública: https://gsgdesign.com.ar/descargas/<slug>
-- =============================================

CREATE TABLE IF NOT EXISTS public.download_pages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'), -- va en la URL y en los QR impresos: no cambiar
  title text NOT NULL,                       -- ej: Fuentes LED
  description text,
  is_active boolean DEFAULT true,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.download_files (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  download_page_id bigint NOT NULL REFERENCES public.download_pages(id) ON DELETE CASCADE,
  title text NOT NULL,                       -- nombre visible del PDF
  path text NOT NULL,                        -- URL pública en R2
  size_bytes bigint,
  display_order integer DEFAULT 0,
  created_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_download_files_page ON public.download_files(download_page_id);

-- RLS: lectura pública, escritura solo service_role (API del backoffice)
ALTER TABLE public.download_pages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.download_files ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "download_pages_select_public" ON public.download_pages;
CREATE POLICY "download_pages_select_public" ON public.download_pages FOR SELECT USING (true);
DROP POLICY IF EXISTS "download_files_select_public" ON public.download_files;
CREATE POLICY "download_files_select_public" ON public.download_files FOR SELECT USING (true);

DROP POLICY IF EXISTS "download_pages_write_service_role" ON public.download_pages;
CREATE POLICY "download_pages_write_service_role" ON public.download_pages
  FOR ALL USING (auth.jwt()->>'role' = 'service_role') WITH CHECK (auth.jwt()->>'role' = 'service_role');
DROP POLICY IF EXISTS "download_files_write_service_role" ON public.download_files;
CREATE POLICY "download_files_write_service_role" ON public.download_files
  FOR ALL USING (auth.jwt()->>'role' = 'service_role') WITH CHECK (auth.jwt()->>'role' = 'service_role');

